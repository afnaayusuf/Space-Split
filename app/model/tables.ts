/** kg/mm³ of the metal named, after the comparative sheet's density tab. */
function metal(material: string): number {
  const m = material.toUpperCase();
  if (/TITAN/.test(m)) return 4.43e-6;
  if (/HAST|C-?276|NICKEL\b/.test(m)) return 8.89e-6;
  if (/INCONEL|MONEL|ALLOY\s*(6|4)/.test(m)) return 8.44e-6;
  if (/CU|COPPER|BRASS/.test(m)) return 8.5e-6;
  if (/ALUMIN/.test(m)) return 2.7e-6;
  if (/SS|STAINLESS|31[0-9]|304|321|347|410|F5[13]|DUPLEX/.test(m)) return 8.0e-6;
  return 7.85e-6;
}

function soft(material: string): number {
  const m = material.toUpperCase();
  if (/PTFE/.test(m)) return 2.15e-6;
  if (/GRAPH|\bFG\b|\/FG/.test(m)) return 1.0e-6;
  if (/RUBBER|NEOPRENE|EPDM|NITRILE|VITON|BUTYL/.test(m)) return 1.5e-6;
  if (/MICA/.test(m)) return 1.0e-6;
  return 2.0e-6; // CNAF, mill board
}

/** A rough weight for one piece, from its outline, for lines that carry no weight. */
export function estimateKg(family: Family, od: number, bore: number, thk: number, material: string): number {
  if (od <= 0) return 0;
  const id = Math.min(Math.max(bore, 0), od);
  const a = (Math.PI / 4) * (od * od - id * id);
  const t = Math.max(thk, 1);
  let kg: number;
  switch (family) {
    case 'SPW':
      kg = a * 3.5 * 6.6e-6;
      break;
    case 'KAM':
      kg = a * t * metal(material) * 0.85;
      break;
    case 'DJ':
      kg = a * t * metal(material) * 0.55;
      break;
    case 'RTJ':
    case 'PLUG':
      kg = a * t * metal(material) * 0.85;
      break;
    case 'ISK':
      kg = a * t * 1.8e-6 * 0.6;
      break;
    default:
      // corrugated metal cores with graphite facing read as SC (CMGC): the core carries the weight
      kg = /CMG|CORRUGATED|CORE/i.test(material) ? a * t * metal(material) * 0.45 : a * t * soft(material);
  }
  return Math.round(kg * 1000) / 1000;
}
