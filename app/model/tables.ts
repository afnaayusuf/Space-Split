/** Outside and inside diameter and height of an R-series ring, or null. */
export function rtj(ringNo: string, style: 'oval' | 'oct' = 'oct'): { od: number; bore: number; thk: number } | null {
  const m = /^R\s*-?\s*(\d{2,3})$/i.exec(ringNo.trim());
  if (!m) return null;
  const row = RINGS[Number(m[1])];
  if (!row) return null;
  const [pd, w] = row;
  const h = RING_HEIGHT[String(w)];
  return { od: +(pd + w).toFixed(2), bore: +(pd - w).toFixed(2), thk: h ? h[style === 'oval' ? 0 : 1] : w * 1.4 };
}

